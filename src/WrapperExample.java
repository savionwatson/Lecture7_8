/**
 * This program demonstrates the use of wrapper classes in Java.
 */
public class WrapperExample {
    public static void main(String[] args) {
        Integer intNumber = 10; // Primitive int to Integer object
        Double doubleNumber = 20.5; // Primitive double to Double object
        System.out.println("Integer: " + intNumber);
        System.out.println("Double: " + doubleNumber);
    }
}
